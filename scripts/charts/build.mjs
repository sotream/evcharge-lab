// Regenerates docs/img/*.svg, docs/metrics.md, docs/drills.md and the generated blocks of README.md (stats, targets at a
// glance, charts, drills table, findings table) from the raw files in docs/load-output and docs/drill-output.
//   node scripts/charts/build.mjs            (set DRILL_OUTPUT_DIR to read drills from another checkout)
import fs from 'node:fs';
import path from 'node:path';
import * as D from './data.mjs';
import { ROOT } from './data.mjs';
import { ALL } from './charts.mjs';
import { metricsMarkdown } from './metrics-table.mjs';
import { statsMarkdown, glanceMarkdown, drillsTable, drillsPage, findingsTable } from './readme-blocks.mjs';

const IMG = path.join(ROOT, 'docs/img');
fs.mkdirSync(IMG, { recursive: true });
const charts = ALL();
// Drop stale generated charts; architecture.svg is hand-made and stays.
for (const f of fs.readdirSync(IMG)) if (f.endsWith('.svg') && f !== 'architecture.svg' && !charts.some((c) => c.file === f)) fs.rmSync(path.join(IMG, f));
for (const c of charts) {
  fs.writeFileSync(path.join(IMG, c.file), c.svg);
  console.log(`wrote docs/img/${c.file} (${c.svg.length} bytes)`);
}

const readme = path.join(ROOT, 'README.md');
let md = fs.readFileSync(readme, 'utf8');
function splice(name, body) {
  const e = `<!-- ${name}:end -->`, a = md.indexOf(`<!-- ${name}:start`), b = md.indexOf(e);
  if (a < 0 || b < a) { console.log(`README.md has no ${name} markers, skipped`); return; }
  const sEnd = md.indexOf('-->', a) + 3;
  md = md.slice(0, sEnd) + '\n' + body + md.slice(b);
  console.log(`updated the ${name} block in README.md`);
}
splice('stats', statsMarkdown(md));
splice('glance', glanceMarkdown());
splice('drills', drillsTable());
splice('findings', findingsTable(md));
// Captions that state a result are computed from the data, never typed.
const ms = D.targetMetrics();
const missed = ms.filter((m) => m.status === 'miss').map((m) => `${m.service}: ${m.metric}`);
const sweep = D.k6List(/^k6-sessions-ocpp-rate/).length;
const drillById = new Map(D.drills().map((d) => [`drill-${d.name}.svg`, d]));
const CAPTIONS = {
  'targets-vs-measured.svg': ['Target versus measured, per service', 'One bar per metric: the measured value divided by the target in `load/targets.json`. ' + (missed.length ? `Bars are red where the measured value misses its target, with no tolerance: ${missed.join('; ')}.` : 'No target is missed in the data present.')],
  'throughput-p99.svg': ['Throughput and p99 per service', 'Achieved rate and p99 latency from the k6 summaries.'],
  'sessions-rate-sweep.svg': ['sessions: latency versus offered rate', `${sweep} constant-arrival-rate runs against \`sessions\`.`],
  'gateway-connections.svg': ['WebSocket connections per gateway instance', 'The 10,000-connection run (one native gateway process) and the k6 runs against one gateway container.'],
  'telemetry-ingest.svg': ['telemetry-ingest: COPY versus row-by-row', 'Sustained rate and durable lag against the offered rate. Hollow markers did not keep up.'],
  'telemetry-storage.svg': ['telemetry storage', 'Compression, chunk sizes and query latency on a 7-day backfill; the full-fleet sizes are derived and marked as such.'],
  'smart-charging-cap.svg': ['smart-charging: allocation under the site cap', 'Drawn power against the sum of the site caps through the allocator outage drill, before, during and after.'],
};
const caption = (f) => CAPTIONS[f] ?? [`Drill timeline: ${f.replace(/^drill-/, '').replace(/\.svg$/, '')}`, `Key series with before, during and after phases and the checks from \`result.json\`. Result: ${drillById.get(f)?.result ? (drillById.get(f).result.pass ? 'PASSED' : 'FAILED') : 'no result.json'}.`];
// Only the headline charts go in the README; telemetry-storage goes to docs/metrics.md, drill timelines to docs/drills.md.
const HEADLINE = Object.keys(CAPTIONS).filter((f) => f !== 'telemetry-storage.svg');
splice('charts', charts.filter((c) => HEADLINE.includes(c.file)).map((c) => { const [t, d] = caption(c.file); return `#### ${t}\n\n${d}\n\n![${t}](docs/img/${c.file})\n`; }).join('\n'));
fs.writeFileSync(readme, md);

const storage = charts.find((c) => c.file === 'telemetry-storage.svg'), [st, sd] = CAPTIONS['telemetry-storage.svg'];
fs.writeFileSync(path.join(ROOT, 'docs/metrics.md'), `# Metrics\n\nThe full metrics table, generated by \`node scripts/charts/build.mjs\` from the raw files in \`docs/load-output/\` and \`docs/drill-output/\`. Every value is labelled measured or derived; the target and verdict columns follow [ADR 0000](adr/0000-requirements-and-capacity.md) with no tolerance. The summary is in the [README](../README.md#targets-at-a-glance).\n\n` + metricsMarkdown('../') + (storage ? `\n## ${st}\n\n${sd}\n\n![${st}](img/${storage.file})\n` : ''));
console.log('wrote docs/metrics.md');
fs.writeFileSync(path.join(ROOT, 'docs/drills.md'), drillsPage());
console.log('wrote docs/drills.md');

if (D.warnings.length) console.log(`\n${D.warnings.length} warning(s):\n${D.warnings.map((w) => `  - ${w}`).join('\n')}`);
